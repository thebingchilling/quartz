/**
 * The WARP generator on Windows, from the desktop app's own components and in the same shape
 * as Android's: WireGuard / AmneziaWG, Advanced options, Generate; once generated only Save to
 * tunnels, which then shows "Saved to tunnels ✓". Entry: Support → WARP generator.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun DesktopWarpScreen(
    onBack: () -> Unit,
    tunnelRepository: TunnelRepository = koinInject(),
    tunnelCoordinator: TunnelCoordinator = koinInject(),
) {
    val warp = remember { DesktopWarp(tunnelRepository, tunnelCoordinator) }
    val scope = rememberCoroutineScope()
    var form by remember { mutableStateOf(DesktopWarpForm()) }
    var generated by remember { mutableStateOf<GeneratedWarp?>(null) }
    var savedForm by remember { mutableStateOf<DesktopWarpForm?>(null) }
    var savedName by remember { mutableStateOf("") }
    var existingName by remember { mutableStateOf<String?>(null) }
    var busy by remember { mutableStateOf(false) }
    var error by remember { mutableStateOf<String?>(null) }
    var showAdvanced by remember { mutableStateOf(false) }

    LaunchedEffect(form.variant, savedForm) { existingName = warp.existing(form.variant)?.name }

    fun update(transform: (DesktopWarpForm) -> DesktopWarpForm) {
        form = transform(form)
        error = null
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("WARP generator") },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back")
                    }
                },
            )
        }
    ) { padding ->
        ScrollableColumn(
            modifier = Modifier.fillMaxSize().padding(padding),
            horizontalAlignment = Alignment.Start,
            verticalArrangement = Arrangement.spacedBy(16.dp, Alignment.Top),
        ) {
            Column {
                WarpVariant.entries.forEach { variant ->
                    SurfaceRow(
                        title = if (variant == WarpVariant.AWG) "AmneziaWG" else "WireGuard",
                        description = {
                            DescriptionText(
                                if (variant == WarpVariant.AWG) "Obfuscated, gets past DPI blocking."
                                else "Standard WireGuard."
                            )
                        },
                        selected = form.variant == variant,
                        onClick = { update { it.copy(variant = variant) } },
                    )
                }
            }
            Column {
                SurfaceRow(
                    leading = { Icon(Icons.Outlined.Tune, contentDescription = null) },
                    title = "Advanced options",
                    trailing = { modifier ->
                        ThemedSwitch(
                            checked = showAdvanced,
                            onClick = { showAdvanced = it },
                            modifier = modifier,
                        )
                    },
                    onClick = { showAdvanced = !showAdvanced },
                )
                if (showAdvanced) AdvancedOptions(form, ::update)

                val result = generated
                val name =
                    existingName ?: WarpConfigBuilder.tunnelName(form.toOptions().slot, form.variant)
                when {
                    result == null ->
                        SurfaceRow(
                            leading = { Icon(Icons.Outlined.Autorenew, contentDescription = null) },
                            title = "Generate WARP config",
                            description = { DescriptionText("Free, valid for 90 days.") },
                            trailing = {
                                ActionButton("Generate", enabled = !busy) {
                                    busy = true
                                    error = null
                                    scope.launch {
                                        runCatching { warp.generate(form.toOptions()) }
                                            .onSuccess { generated = it }
                                            .onFailure { error = it.message ?: it.toString() }
                                        busy = false
                                    }
                                }
                            },
                        )
                    savedForm == form ->
                        SurfaceRow(
                            leading = {
                                Icon(
                                    Icons.Outlined.CheckCircle,
                                    contentDescription = null,
                                    tint = MaterialTheme.colorScheme.primary,
                                )
                            },
                            title = "Saved to tunnels",
                            description = { DescriptionText("$savedName is up to date") },
                        )
                    else ->
                        SurfaceRow(
                            leading = { Icon(Icons.Outlined.SaveAlt, contentDescription = null) },
                            title = "Save to tunnels",
                            description = {
                                DescriptionText(
                                    if (existingName != null) "Replaces $name" else "Adds it as $name"
                                )
                            },
                            trailing = {
                                ActionButton("Save", enabled = !busy) {
                                    busy = true
                                    error = null
                                    val snapshot = form
                                    scope.launch {
                                        runCatching { warp.save(result, snapshot.toOptions()) }
                                            .onSuccess {
                                                savedName = it
                                                savedForm = snapshot
                                            }
                                            .onFailure { error = it.message ?: it.toString() }
                                        busy = false
                                    }
                                }
                            },
                        )
                }
                error?.let {
                    Text(
                        it,
                        color = MaterialTheme.colorScheme.error,
                        style = MaterialTheme.typography.bodySmall,
                        modifier = Modifier.padding(horizontal = 16.dp),
                    )
                }
            }
        }
    }
}

@Composable
private fun ActionButton(text: String, enabled: Boolean, onClick: () -> Unit) {
    Button(onClick = onClick, enabled = enabled) {
        Text(
            text,
            fontWeight = FontWeight.Bold,
            style = MaterialTheme.typography.bodyMedium.copy(color = MaterialTheme.colorScheme.surface),
        )
    }
}

@Composable
private fun AdvancedOptions(
    form: DesktopWarpForm,
    update: ((DesktopWarpForm) -> DesktopWarpForm) -> Unit,
) {
    Column(
        verticalArrangement = Arrangement.spacedBy(12.dp),
        modifier = Modifier.padding(horizontal = 16.dp, vertical = 8.dp),
    ) {
        ConfigurationTextBox(
            value = form.endpoint,
            onValueChange = { v -> update { it.copy(endpoint = v) } },
            label = "Endpoint",
            hint = "Default",
            trailing = {
                IconButton(onClick = { update { it.copy(endpoint = WarpEndpoints.random()) } }) {
                    Icon(Icons.Outlined.Casino, contentDescription = "Pick another")
                }
            },
            modifier = Modifier.fillMaxWidth(),
        )
        Field("DNS servers", form.dns) { v -> update { it.copy(dns = v) } }
        Field("MTU", form.mtu) { v -> update { it.copy(mtu = v) } }
        Field("Allowed IPs", form.allowedIps) { v -> update { it.copy(allowedIps = v) } }
        Field("Persistent keepalive", form.keepalive) { v -> update { it.copy(keepalive = v) } }
        Field("Device type", form.deviceType) { v -> update { it.copy(deviceType = v) } }
        Field("Locale", form.locale) { v -> update { it.copy(locale = v) } }
        if (form.variant == WarpVariant.AWG) {
            Field("Jc", form.jc) { v -> update { it.copy(jc = v) } }
            Field("Jmin", form.jMin) { v -> update { it.copy(jMin = v) } }
            Field("Jmax", form.jMax) { v -> update { it.copy(jMax = v) } }
        }
    }
}

@Composable
private fun Field(label: String, value: String, onChange: (String) -> Unit) {
    ConfigurationTextBox(
        value = value,
        onValueChange = onChange,
        label = label,
        modifier = Modifier.fillMaxWidth(),
    )
}
